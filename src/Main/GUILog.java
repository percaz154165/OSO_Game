    private void conectarActionPerformed(java.awt.event.ActionEvent evt) {                                         
        // TODO add your handling code here:
        this.conectar.setEnabled(false);
        this.juego = new JuegoOso(this.send,this.tablero,this.OSOSLOC,this.OSOSRIV,this.PUERTOJUEGO.getText(),this.IPJUEGO.getText(),this.USUARIO.getText());
        this.chat = new ChatConfig(this.enviar, this.USUARIO, this.MENSAJE, this.CHAT,this.PUERTOCHAT.getText(),this.IPCHAT.getText());
        this.chat.start();
        this.juego.start();
    }                                        

